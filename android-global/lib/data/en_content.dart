    '霜降': 'Frost Descent',
    '立冬': 'Start of Winter',
    '小雪': 'Minor Snow',
    '大雪': 'Major Snow',
    '冬至': 'Winter Solstice',
    '小寒': 'Minor Cold',
    '大寒': 'Major Cold',
  };

  /// Map solar term name: returns English if Chinese detected, otherwise original
  static String solarTerm(String? zh) {
    if (zh == null) return '';
    return solarTerms[zh] ?? zh;
  }

  /// Check if a string contains Chinese characters
  static bool isChinese(String? text) {
    if (text == null || text.isEmpty) return false;
    return RegExp(r'[\u4e00-\u9fff]').hasMatch(text);
  }

  /// Get English solar term name, preferring name_en field, falling back to mapper
  static String solarTermFromApi(Map<String, dynamic>? data) {
    if (data == null) return '';
    final nameEn = data['name_en']?.toString();
    if (nameEn != null && nameEn.isNotEmpty && !isChinese(nameEn)) return nameEn;
    final name = data['name']?.toString() ?? '';
    return solarTerm(name);
  }
}
