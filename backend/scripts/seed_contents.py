def seed():
    conn = sqlite3.connect(str(DB_PATH))
    cursor = conn.cursor()
    now = datetime.now().strftime("%Y-%m-%dT%H:%M:%SZ")
    inserted = 0

    for item in SEED_CONTENTS:
        (id_, title, desc, type_, category, tags, difficulty, time_, duration,
         ingredients, steps, location, method, effect, benefits,
         best_time, season_tag) = item
        try:
            cursor.execute("""
                INSERT OR IGNORE INTO contents
                (id, title, description, type, category, tags, difficulty, time, duration,
                 ingredients, steps, location, method, effect, benefits, best_time,
                 season_tag, locale, view_count, like_count, is_premium, created_at, image_url)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """, (id_, title, desc, type_, category, tags, difficulty, time_, duration,
                  ingredients, steps, location, method, effect, benefits, best_time,
                  season_tag, "zh-CN", 0, 0, 0, now, ""))
            if cursor.rowcount > 0:
                inserted += 1
        except Exception as e:
            print(f"  Error inserting {id_}: {e}")

    conn.commit()
    print(f"[Seed] Inserted {inserted} new content records into contents table")
    conn.close()


if __name__ == "__main__":
    seed()
